// Generates apple/Sources/SmokeshowKit/Design/Tokens.generated.swift from
// design/tokens.json — the same parity source scripts/generate-tokens.mjs reads
// for the web. Colours, type scale, radii, and motion therefore cannot drift
// between smokeshow.earth and the Apple apps: they are one file, compiled twice.
//
// Do not hand-edit Tokens.generated.swift. Edit design/tokens.json and run
// `npm run tokens:apple`.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const tokens = JSON.parse(readFileSync(path.join(root, 'design/tokens.json'), 'utf8'));
const outPath = path.join(root, 'apple/Sources/SmokeshowKit/Design/Tokens.generated.swift');

// rem → points. The web's root font-size is 16px; Apple sizes are points and
// are scaled at render time with Dynamic Type (see Typography.swift), so this
// conversion sets the *base* size only.
const REM_PT = 16;
const rem = (v) => {
  const n = Number.parseFloat(v);
  if (Number.isNaN(n)) throw new Error(`token "${v}" is not a rem value`);
  return Number((n * REM_PT).toFixed(2));
};
const seconds = (v) => Number(Number.parseFloat(v).toFixed(3));

const hexToRGB = (hex) => {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => Number.parseInt(h.slice(i, i + 2), 16));
};

const colorCase = (name, hex) => {
  const [r, g, b] = hexToRGB(hex);
  return `        /// \`${hex}\`\n        public static let ${name} = TokenColor(hex: 0x${hex.replace('#', '').toUpperCase()}, r: ${r}, g: ${g}, b: ${b})`;
};

const palette = (scheme) =>
  Object.entries(tokens.color[scheme])
    .map(([name, hex]) => colorCase(name, hex))
    .join('\n');

const typeScale = Object.entries(tokens.typeScale)
  .map(([name, value]) => `        public static let ${name}: CGFloat = ${rem(value)}`)
  .join('\n');

const radii = Object.entries(tokens.radius)
  .map(([name, value]) =>
    name === 'pill'
      ? `        /// \`999px\` on the web — a capsule here.\n        public static let pill: CGFloat = 999`
      : `        public static let ${name}: CGFloat = ${rem(value)}`,
  )
  .join('\n');

const motion = Object.entries(tokens.motion)
  .map(
    ([name, { duration, easing }]) =>
      `        /// \`${duration} ${easing}\`\n        public static let ${name} = MotionToken(duration: ${seconds(duration)}, easing: .${easing === 'ease-in-out' ? 'easeInOut' : 'ease'})`,
  )
  .join('\n');

const swift = `// Generated by scripts/generate-apple-tokens.mjs from design/tokens.json.
// Do not edit by hand — edit the JSON and re-run \`npm run tokens:apple\`.
//
// design/tokens.json is the parity source shared with the web build
// (src/styles/tokens.css is generated from the same file). If a colour here
// disagrees with the web, the JSON is wrong, not this file.

import CoreGraphics

public enum Tokens {

    /// A colour token, carried as both its source hex and its integer channels
    /// so a platform \`Color\` can be built without parsing strings.
    public struct TokenColor: Sendable, Equatable {
        public let hex: UInt32
        public let r: Int
        public let g: Int
        public let b: Int

        public init(hex: UInt32, r: Int, g: Int, b: Int) {
            self.hex = hex
            self.r = r
            self.g = g
            self.b = b
        }
    }

    public struct MotionToken: Sendable, Equatable {
        public enum Easing: Sendable { case ease, easeInOut }
        public let duration: Double
        public let easing: Easing

        public init(duration: Double, easing: Easing) {
            self.duration = duration
            self.easing = easing
        }
    }

    public enum Color {
        public enum Dark {
${palette('dark')}
        }

        public enum Light {
${palette('light')}
        }
    }

    /// Base point sizes, converted from the web's rem scale at a 16pt root.
    /// Render them through \`Typography\` so Dynamic Type still applies.
    public enum TypeScale {
${typeScale}
    }

    public enum Radius {
${radii}
    }

    public enum Motion {
${motion}
    }
}
`;

mkdirSync(path.dirname(outPath), { recursive: true });
writeFileSync(outPath, swift);
console.log(`✓ ${path.relative(root, outPath)}`);
